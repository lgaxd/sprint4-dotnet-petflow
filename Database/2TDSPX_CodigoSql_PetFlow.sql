-- -------------------------
-- Relatorio 7.1
-- Extrato de pontos por tutor com classificacao de nivel
-- -------------------------
DECLARE
  CURSOR c_pontos IS
    SELECT
      t.name       AS tutor_nome,
      SUM(rp.points) AS total_pontos
    FROM tutor t
    JOIN reward_point rp ON rp.tutor_id = t.id
    GROUP BY t.name
    ORDER BY total_pontos DESC;

  v_nivel      VARCHAR2(20);
  v_total_geral NUMBER := 0;
BEGIN
  DBMS_OUTPUT.PUT_LINE('==============================================');
  DBMS_OUTPUT.PUT_LINE('RELATORIO 1: EXTRATO DE PONTOS POR TUTOR');
  DBMS_OUTPUT.PUT_LINE('==============================================');
  DBMS_OUTPUT.PUT_LINE(RPAD('Tutor',25) || LPAD('Pontos',12) || RPAD('  Nivel',15));
  DBMS_OUTPUT.PUT_LINE(RPAD('-',52,'-'));

  FOR r IN c_pontos LOOP
    v_total_geral := v_total_geral + r.total_pontos;

    v_nivel := CASE
      WHEN r.total_pontos >= 500 THEN 'OURO'
      WHEN r.total_pontos >= 200 THEN 'PRATA'
      WHEN r.total_pontos >= 100 THEN 'BRONZE'
      ELSE                            'INICIANTE'
    END;

    DBMS_OUTPUT.PUT_LINE(
      RPAD(r.tutor_nome, 25) ||
      LPAD(r.total_pontos, 12) ||
      '  ' || v_nivel
    );
  END LOOP;

  DBMS_OUTPUT.PUT_LINE(RPAD('-',52,'-'));
  DBMS_OUTPUT.PUT_LINE(RPAD('TOTAL GERAL', 25) || LPAD(v_total_geral, 12));
END;
/

-- -------------------------
-- Relatorio 7.2
-- Status dos pets por tutor com alertas de risco
-- -------------------------
DECLARE
  CURSOR c_pets_risco IS
    SELECT
      t.name        AS tutor_nome,
      p.name        AS pet_nome,
      s.name        AS especie,
      rs.score      AS score_risco,
      rl.name       AS nivel_risco
    FROM pet p
    JOIN tutor      t  ON t.id  = p.tutor_id
    JOIN species    s  ON s.id  = p.species_id
    LEFT JOIN (
      SELECT pet_id, score, risk_level_id,
             ROW_NUMBER() OVER (PARTITION BY pet_id ORDER BY calculated_at DESC) AS rn
      FROM risk_score
    ) rs ON rs.pet_id = p.id AND rs.rn = 1
    LEFT JOIN risk_level rl ON rl.id = rs.risk_level_id
    ORDER BY t.name, rs.score DESC NULLS LAST;

  v_alerta    VARCHAR2(50);
  v_qtd_alto  NUMBER := 0;
  v_qtd_total NUMBER := 0;
BEGIN
  DBMS_OUTPUT.PUT_LINE('==============================================');
  DBMS_OUTPUT.PUT_LINE('RELATORIO 2: SITUACAO DE RISCO DOS PETS');
  DBMS_OUTPUT.PUT_LINE('==============================================');
  DBMS_OUTPUT.PUT_LINE(RPAD('Tutor',20) || RPAD('Pet',15) || RPAD('Especie',12) || LPAD('Score',8) || RPAD('  Nivel',12) || 'Alerta');
  DBMS_OUTPUT.PUT_LINE(RPAD('-',85,'-'));

  FOR r IN c_pets_risco LOOP
    v_qtd_total := v_qtd_total + 1;

    IF r.nivel_risco IN ('Alto','Critico') THEN
      v_alerta   := '*** ATENCAO ***';
      v_qtd_alto := v_qtd_alto + 1;
    ELSIF r.nivel_risco = 'Medio' THEN
      v_alerta := 'Monitorar';
    ELSE
      v_alerta := 'Ok';
    END IF;

    DBMS_OUTPUT.PUT_LINE(
      RPAD(r.tutor_nome,  20) ||
      RPAD(r.pet_nome,    15) ||
      RPAD(r.especie,     12) ||
      LPAD(NVL(TO_CHAR(r.score_risco), '-'), 8) ||
      '  ' || RPAD(NVL(r.nivel_risco, '-'), 12) ||
      v_alerta
    );
  END LOOP;

  DBMS_OUTPUT.PUT_LINE(RPAD('-',85,'-'));
  DBMS_OUTPUT.PUT_LINE('Total de pets analisados : ' || v_qtd_total);
  DBMS_OUTPUT.PUT_LINE('Pets em situacao de risco: ' || v_qtd_alto);
END;
/

-- -------------------------
-- Relatorio 7.3
-- Cupons disponiveis agrupados por parceiro e tipo de desconto
-- -------------------------
DECLARE
  CURSOR c_cupons IS
    SELECT
      pd.partner_name                   AS parceiro,
      ct.discount_type                  AS tipo_desconto,
      COUNT(cu.id)                      AS qtd_cupons,
      SUM(ct.discount_value)            AS valor_total_descontos,
      MIN(ct.points_required)           AS menor_custo_pts,
      MAX(ct.points_required)           AS maior_custo_pts
    FROM coupon cu
    JOIN coupon_template  ct ON ct.id = cu.template_id
    JOIN partner_discount pd ON pd.id = ct.partner_discount_id
    WHERE cu.status = 'DISPONIVEL'
    GROUP BY pd.partner_name, ct.discount_type
    ORDER BY pd.partner_name, ct.discount_type;

  v_subtotal_qtd    NUMBER := 0;
  v_subtotal_valor  NUMBER := 0;
  v_parceiro_atual  VARCHAR2(100) := '';
BEGIN
  DBMS_OUTPUT.PUT_LINE('==============================================');
  DBMS_OUTPUT.PUT_LINE('RELATORIO 3: CUPONS DISPONIVEIS POR PARCEIRO');
  DBMS_OUTPUT.PUT_LINE('==============================================');
  DBMS_OUTPUT.PUT_LINE(RPAD('Parceiro',25) || RPAD('Tipo',15) || LPAD('Qtd',8) || LPAD('Valor Total',15) || LPAD('Pts Min',10) || LPAD('Pts Max',10));
  DBMS_OUTPUT.PUT_LINE(RPAD('-',83,'-'));

  FOR r IN c_cupons LOOP
    IF v_parceiro_atual != r.parceiro AND v_parceiro_atual != '' THEN
      DBMS_OUTPUT.PUT_LINE(RPAD(' >> Sub-Total ' || v_parceiro_atual, 40) ||
                           LPAD(v_subtotal_qtd, 8) ||
                           LPAD(TO_CHAR(v_subtotal_valor,'FM99990.00'), 15));
      DBMS_OUTPUT.PUT_LINE(RPAD('-',83,'-'));
      v_subtotal_qtd   := 0;
      v_subtotal_valor := 0;
    END IF;

    v_parceiro_atual := r.parceiro;
    v_subtotal_qtd   := v_subtotal_qtd   + r.qtd_cupons;
    v_subtotal_valor := v_subtotal_valor + r.valor_total_descontos;

    DBMS_OUTPUT.PUT_LINE(
      RPAD(r.parceiro,       25) ||
      RPAD(r.tipo_desconto,  15) ||
      LPAD(r.qtd_cupons,      8) ||
      LPAD(TO_CHAR(r.valor_total_descontos,'FM99990.00'), 15) ||
      LPAD(r.menor_custo_pts, 10) ||
      LPAD(r.maior_custo_pts, 10)
    );
  END LOOP;

  IF v_parceiro_atual != '' THEN
    DBMS_OUTPUT.PUT_LINE(RPAD(' >> Sub-Total ' || v_parceiro_atual, 40) ||
                         LPAD(v_subtotal_qtd, 8) ||
                         LPAD(TO_CHAR(v_subtotal_valor,'FM99990.00'), 15));
  END IF;
END;
