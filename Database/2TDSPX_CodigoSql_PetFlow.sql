-- =============================================================
-- ATENCAO: este script RECRIA o schema do zero. A secao 1 apaga
-- (DROP TABLE ... CASCADE CONSTRAINTS) todas as tabelas do PetFlow
-- antes de cria-las. Execute-o apenas em um schema vazio/de teste;
-- NAO o execute no schema que a API Java esta usando (os dados e
-- os pacotes da aplicacao seriam perdidos).
-- Alinhado a aplicacao Java (Sprint 4): status validos --
--   health_event: AGENDADO, REALIZADO, CANCELADO
--   subscription: ATIVO, ENCERRADO, CANCELADO, EXPIRADO
--   coupon:       DISPONIVEL, RESGATADO, UTILIZADO
-- =============================================================

-- =============================================================
-- PetFlow - SCRIPT COMPLETO ORACLE
-- Materia: Mastering Relational and Non-Relational Database
-- =============================================================
-- ORDEM DE EXECUCAO:
-- 1. DDL (criacao das tabelas)
-- 2. Tabela de log de erros
-- 3. Procedures de carga de dados
-- 4. Chamadas das procedures (carga inicial)
-- 5. Blocos anonimos de consulta (joins, group by, order by)
-- 6. Bloco LAG / LEAD (linha anterior, atual, proxima)
-- 7. Relatorios com cursor explicito
-- =============================================================


-- =============================================================
-- SECAO 1: DDL - CRIACAO DAS TABELAS
-- =============================================================

-- Limpa tabelas na ordem correta (filho antes do pai)
BEGIN
  FOR t IN (
    SELECT table_name FROM user_tables
    WHERE table_name IN (
      'REDEEM','COUPON','COUPON_TEMPLATE','PARTNER_DISCOUNT',
      'REWARD_POINT','RISK_SCORE','HEALTH_EVENT',
      'SUBSCRIPTION','PLAN','ADDRESS',
      'PET','CLINIC','TUTOR',
      'REWARD_ACTION','EVENT_TYPE','RISK_LEVEL','SPECIES',
      'LOG_ERROS', 'LOG_AUDITORIA_HEALTH_EVENT'
    )
  ) LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS';
  END LOOP;
END;
/

-- -------------------------
-- Tabelas de dominio
-- -------------------------

CREATE TABLE species (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR2(50)  UNIQUE NOT NULL,
  description VARCHAR2(200)
);

CREATE TABLE event_type (
  id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          VARCHAR2(50)  UNIQUE NOT NULL,
  points_reward NUMBER        NOT NULL,
  category      VARCHAR2(50)  NOT NULL
  -- categoria: 'PREVENTIVO', 'TERAPEUTICO', 'BEM_ESTAR', 'EMERGENCIA'
);

CREATE TABLE reward_action (
  id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         VARCHAR2(50)  UNIQUE NOT NULL,
  points_value NUMBER        NOT NULL,
  description  VARCHAR2(200)
);

CREATE TABLE risk_level (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR2(50)  UNIQUE NOT NULL,
  description VARCHAR2(200),
  min_score   NUMBER        NOT NULL,
  max_score   NUMBER        NOT NULL
);

-- -------------------------
-- Entidades principais
-- -------------------------

CREATE TABLE tutor (
  id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role          VARCHAR2(20) DEFAULT 'TUTOR' NOT NULL,  -- <-- ADICIONADO
  name          VARCHAR2(100) NOT NULL,
  email         VARCHAR2(100) UNIQUE NOT NULL,
  phone         VARCHAR2(20),
  password_hash VARCHAR2(255) NOT NULL,
  created_at    TIMESTAMP     DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE address (
  id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tutor_id  NUMBER        NOT NULL,
  street    VARCHAR2(200) NOT NULL,
  city      VARCHAR2(100) NOT NULL,
  state     VARCHAR2(50)  NOT NULL,
  zip_code  VARCHAR2(10)  NOT NULL,
  CONSTRAINT fk_address_tutor FOREIGN KEY (tutor_id) REFERENCES tutor(id)
);

CREATE TABLE clinic (
  id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       VARCHAR2(100) NOT NULL,
  address    VARCHAR2(200),
  phone      VARCHAR2(20),
  cnpj       VARCHAR2(18)  UNIQUE,
  created_at TIMESTAMP     DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE pet (
  id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tutor_id   NUMBER        NOT NULL,
  species_id NUMBER        NOT NULL,
  name       VARCHAR2(100) NOT NULL,
  breed      VARCHAR2(50),
  birth_date DATE,
  weight     NUMBER(5,2),
  created_at TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_pet_tutor   FOREIGN KEY (tutor_id)   REFERENCES tutor(id),
  CONSTRAINT fk_pet_species FOREIGN KEY (species_id) REFERENCES species(id)
);

-- -------------------------
-- Planos e assinaturas
-- -------------------------

CREATE TABLE plan (
  id               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clinic_id        NUMBER        NOT NULL,
  name             VARCHAR2(100) NOT NULL,
  description      VARCHAR2(200),
  price            NUMBER(10,2)  NOT NULL,
  duration_days    NUMBER        NOT NULL,
  points_per_event NUMBER        DEFAULT 1 NOT NULL,
  -- multiplicador: plano premium pode dar 2x pontos por evento
  CONSTRAINT fk_plan_clinic FOREIGN KEY (clinic_id) REFERENCES clinic(id)
);

CREATE TABLE subscription (
  id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pet_id     NUMBER       NOT NULL,
  plan_id    NUMBER       NOT NULL,
  start_date DATE         NOT NULL,
  end_date   DATE,
  status     VARCHAR2(20) NOT NULL,
  -- status: 'ATIVO', 'ENCERRADO', 'CANCELADO', 'EXPIRADO'
  created_at TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_sub_pet  FOREIGN KEY (pet_id)  REFERENCES pet(id),
  CONSTRAINT fk_sub_plan FOREIGN KEY (plan_id) REFERENCES plan(id)
);

-- -------------------------
-- Saude do pet
-- -------------------------

CREATE TABLE health_event (
  id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pet_id        NUMBER        NOT NULL,
  event_type_id NUMBER        NOT NULL,
  clinic_id     NUMBER,
  description   VARCHAR2(200),
  event_date    DATE          NOT NULL,
  status        VARCHAR2(20)  NOT NULL,
  -- status: 'AGENDADO', 'REALIZADO', 'CANCELADO'
  created_at    TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_he_pet        FOREIGN KEY (pet_id)        REFERENCES pet(id),
  CONSTRAINT fk_he_event_type FOREIGN KEY (event_type_id) REFERENCES event_type(id),
  CONSTRAINT fk_he_clinic     FOREIGN KEY (clinic_id)     REFERENCES clinic(id)
);

-- -------------------------
-- Recompensas
-- -------------------------

CREATE TABLE reward_point (
  id               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tutor_id         NUMBER        NOT NULL,
  reward_action_id NUMBER        NOT NULL,
  points           NUMBER        NOT NULL,
  reference_type   VARCHAR2(50),
  -- ex: 'HEALTH_EVENT', 'SUBSCRIPTION', 'CADASTRO_PET'
  reference_id     NUMBER,
  -- id do registro que gerou os pontos
  created_at       TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_rp_tutor  FOREIGN KEY (tutor_id)         REFERENCES tutor(id),
  CONSTRAINT fk_rp_action FOREIGN KEY (reward_action_id) REFERENCES reward_action(id)
);

-- -------------------------
-- Parceiros e cupons
-- -------------------------

CREATE TABLE partner_discount (
  id               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clinic_id        NUMBER        NOT NULL,
  partner_name     VARCHAR2(100) NOT NULL,
  category         VARCHAR2(50)  NOT NULL,
  -- categoria: 'RACAO', 'PETSHOP', 'MEDICAMENTO', 'CONSULTA'
  discount_percent NUMBER(5,2)   NOT NULL,
  CONSTRAINT fk_pd_clinic FOREIGN KEY (clinic_id) REFERENCES clinic(id)
);

CREATE TABLE coupon_template (
  id                 NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  partner_discount_id NUMBER       NOT NULL,
  title              VARCHAR2(100) NOT NULL,
  discount_value     NUMBER(10,2)  NOT NULL,
  discount_type      VARCHAR2(20)  NOT NULL,
  -- tipo: 'PERCENTUAL', 'VALOR_FIXO'
  points_required    NUMBER        NOT NULL,
  CONSTRAINT fk_ct_partner FOREIGN KEY (partner_discount_id) REFERENCES partner_discount(id)
);

CREATE TABLE coupon (
  id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  template_id     NUMBER       NOT NULL,
  code            VARCHAR2(50) UNIQUE NOT NULL,
  status          VARCHAR2(20) NOT NULL,
  -- status: 'DISPONIVEL', 'RESGATADO', 'UTILIZADO'
  expiration_date DATE,
  created_at      TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_coupon_template FOREIGN KEY (template_id) REFERENCES coupon_template(id)
);

CREATE TABLE redeem (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tutor_id    NUMBER    NOT NULL,
  coupon_id   NUMBER    NOT NULL,
  points_used NUMBER    NOT NULL,
  created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_redeem_tutor  FOREIGN KEY (tutor_id)  REFERENCES tutor(id),
  CONSTRAINT fk_redeem_coupon FOREIGN KEY (coupon_id) REFERENCES coupon(id)
);

-- -------------------------
-- Score de risco
-- -------------------------

CREATE TABLE risk_score (
  id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pet_id        NUMBER    NOT NULL,
  score         NUMBER    NOT NULL,
  risk_level_id NUMBER    NOT NULL,
  calculated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_rs_pet   FOREIGN KEY (pet_id)        REFERENCES pet(id),
  CONSTRAINT fk_rs_level FOREIGN KEY (risk_level_id) REFERENCES risk_level(id)
);


-- =============================================================
-- SECAO 2: TABELA DE LOG DE ERROS
-- Usada por todas as procedures para registrar excecoes
-- =============================================================

CREATE TABLE log_erros (
  id               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  procedure_name   VARCHAR2(100) NOT NULL,
  usuario          VARCHAR2(100) NOT NULL,
  data_ocorrencia  TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
  codigo_erro      NUMBER,
  mensagem_erro    VARCHAR2(4000)
);


-- =============================================================
-- SECAO 3: PROCEDURES DE CARGA DE DADOS
-- Uma procedure por tabela, com passagem de parametros,
-- tratamento de excecao (WHEN OTHERS + 2 excecoes especificas)
-- e log de erros.
-- =============================================================

-- -------------------------
-- 3.1 SPECIES
-- -------------------------
CREATE OR REPLACE PROCEDURE sp_insert_species (
  p_name        IN species.name%TYPE,
  p_description IN species.description%TYPE
) AS
  v_usuario VARCHAR2(100);
  v_sqlcode NUMBER;
  v_sqlerrm VARCHAR2(4000);
  ex_nome_nulo   EXCEPTION;
  ex_duplicado   EXCEPTION;
  PRAGMA EXCEPTION_INIT(ex_duplicado, -1);
BEGIN
  v_usuario := USER;
  IF p_name IS NULL THEN
    RAISE ex_nome_nulo;
  END IF;

  INSERT INTO species (name, description)
  VALUES (p_name, p_description);

  COMMIT;

EXCEPTION
  WHEN ex_nome_nulo THEN
    INSERT INTO log_erros (procedure_name, usuario, codigo_erro, mensagem_erro)
    VALUES ('sp_insert_species', v_usuario, -20001, 'Nome da especie nao pode ser nulo');
    COMMIT;
    RAISE_APPLICATION_ERROR(-20001, 'Nome da especie nao pode ser nulo');

  WHEN ex_duplicado THEN
    INSERT INTO log_erros (procedure_name, usuario, codigo_erro, mensagem_erro)
    VALUES ('sp_insert_species', v_usuario, -1, 'Especie ja cadastrada: ' || p_name);
    COMMIT;
    RAISE_APPLICATION_ERROR(-20002, 'Especie ja cadastrada: ' || p_name);

  WHEN OTHERS THEN
    v_sqlcode := SQLCODE;
    v_sqlerrm := SQLERRM;
    INSERT INTO log_erros (procedure_name, usuario, codigo_erro, mensagem_erro)
    VALUES ('sp_insert_species', v_usuario, v_sqlcode, v_sqlerrm);
    COMMIT;
    RAISE;
END sp_insert_species;
/

